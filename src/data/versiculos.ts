export function getVersiculoDelDia(fecha: Date = new Date()): Versiculo {
	const inicio = new Date(fecha.getFullYear(), 0, 0);
	const diff = fecha.getTime() - inicio.getTime();
	const diaDelAnio = Math.floor(diff / (1000 * 60 * 60 * 24));
	const indice = diaDelAnio % versiculos.length;
	return versiculos[indice];
}
